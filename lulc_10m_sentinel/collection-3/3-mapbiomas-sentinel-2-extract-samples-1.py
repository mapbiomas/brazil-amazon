collection = (
    ee.ImageCollection(ASSET_MOSAICS[0]).merge(ee.ImageCollection(ASSET_MOSAICS[1]))
    .filter(ee.Filter.eq('version', MOSAIC_VERSION))
    .filter(ee.Filter.eq('biome', 'AMAZONIA'))
    )

print(collection.size().getInfo())

if len(GRID_NAMES) == 0:
    # Empty GRID_NAMES means "discover all available grids from the mosaics".
    GRID_NAMES = collection.aggregate_histogram('grid_name').getInfo().keys()

print(GRID_NAMES)

# TRAINED holds table (FeatureCollection) assets, not an ImageCollection,
# so existing outputs are enumerated via the asset listing API instead.
alreadyInCollection = [
    asset['name'].split('/')[-1]
    for asset in ee.data.listAssets({'parent': ASSET_OUTPUT})['assets']
]

for year in YEARS:

    collectionYear = collection.filterMetadata('year', 'equals', year)

    # The annual embedding image is appended as extra predictors for sampling.
    embeddingImage = ee.Image(EMBEDDING_COLLECTION
      .filterDate(f'{year}-01-01', f'{year}-12-31')
      .mosaic())

    for gridName in GRID_NAMES:

        samplesName = '{}-{}-{}'.format(gridName, year, OUTPUT_VERSION)

        # Avoid resubmitting exports that are already present in the TRAINED folder.
        if samplesName in alreadyInCollection:
            continue

        try:

            image = collectionYear.filter(
                ee.Filter.eq('grid_name', gridName)).first()

            image = ee.Image(image)
            
            composite = image.addBands(embeddingImage)

            region = image.geometry()

            similarMask = ee.Image('{}/{}-SEGMENTS-{}-{}-{}'.format(
                ASSET_SEGMENTS, gridName, year, N_SAMPLES, SEGMENTS_VERSION))

            # Sample only inside labeled segments propagated from stable references.
            composite = composite.mask(similarMask.neq(0))

            samples = composite\
                .select(FEAT_SPACE_BANDS + EMBEDDING_BANDS)\
                .addBands(similarMask)\
                .sample(
                    region=region,
                    scale=10,
                    factor=FACTOR_SAMPLES,
                    dropNulls=True,
                    geometries=True,
                    tileScale=16
                )
            
            
            samplesName = '{}-{}-{}'.format(gridName, year, OUTPUT_VERSION)

            task = ee.batch.Export.table.toAsset(
                collection=samples,
                description=samplesName,
                assetId='{}/{}'.format(ASSET_OUTPUT, samplesName),
            )

            print('Exporting {}...'.format(samplesName))

            task.start()
        except Exception as e:
            print(e)
