"""Sentinel Collection 3 stage 3: extract training samples.

This script samples pixels from the segment masks exported by stage 2 and
joins them with Sentinel-2 spectral features plus annual Google Satellite
Embedding bands. The result is a per-grid, per-year training table exported
to Earth Engine assets.

Inputs:
- Sentinel-2 mosaic collections filtered by biome and mosaic version
- Segment-mask assets generated by stage 2
- `GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL` for each year in `YEARS`

Outputs:
- Training table assets under `.../SAMPLES/AMAZONIA/TRAINED`

Run this after stage 2 and before stage 4. This script skips assets already
present in the output folder, so version constants and year lists should be
changed carefully.
"""
import ee
from pprint import pprint

ee.Initialize(project='mapbiomas-colombia')

ASSET_MOSAICS = [
    'projects/nexgenmap/MapBiomas2/SENTINEL/mosaics-3',
    'projects/mapbiomas-mosaics/assets/SENTINEL/BRAZIL/mosaics-3'
    ]

ASSET_SEGMENTS = 'projects/mapbiomas-brazil/assets/LAND-COVER-10M/COLLECTION-3/SAMPLES/AMAZONIA/SEGMENTS'

ASSET_OUTPUT = 'projects/mapbiomas-brazil/assets/LAND-COVER-10M/COLLECTION-3/SAMPLES/AMAZONIA/TRAINED'

EMBEDDING_COLLECTION = ee.ImageCollection('GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL')

