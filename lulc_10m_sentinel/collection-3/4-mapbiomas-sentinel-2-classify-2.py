collection = (
    ee.ImageCollection(ASSET_MOSAICS[0]).merge(ee.ImageCollection(ASSET_MOSAICS[1]))
    .filter(ee.Filter.eq('version', MOSAIC_VERSION))
    .filter(ee.Filter.eq('biome', 'AMAZONIA'))
    )

if len(GRID_NAMES) == 0:
    # Empty GRID_NAMES means "classify every grid available in the mosaics".
    GRID_NAMES = collection.aggregate_histogram('grid_name').getInfo().keys()

print(GRID_NAMES)

alreadyInCollection = ee.ImageCollection(ASSET_OUTPUT) \
    .filterMetadata('version', 'equals', OUTPUT_VERSION) \
    .reduceColumns(
        ee.Reducer.toList(),
        ['system:index']) \
    .get('list').getInfo()

for year in YEARS:

    collectionYear = collection.filter('year == {}'.format(year))

    # Keep the classifier input schema aligned with stage 3 sample extraction.
    embeddingImage = ee.Image(EMBEDDING_COLLECTION
      .filterDate(f'{year}-01-01', f'{year}-12-31')
      .mosaic())
    
    for gridName in GRID_NAMES:

        imageName = '{}-{}-{}'.format(gridName, year, OUTPUT_VERSION)

        # Skip exports that already exist for this versioned grid/year output.
        if imageName not in alreadyInCollection:
            try:
                samplesName = '{}/{}-{}-{}'.format(ASSET_SAMPLES,
                                                gridName, year, SAMPLES_VERSION)

                image = collectionYear.filterMetadata(
                    'grid_name', 'equals', gridName).first()

                image = ee.Image(image)
                
                composite = image.addBands(embeddingImage)

                # Expand the export region slightly to avoid edge clipping on tile bounds.
                geometry = image.geometry().buffer(300).bounds()
                
                samples = ee.FeatureCollection(samplesName)

                print('n samples:', samples.size().getInfo())

                classHistogram = samples.aggregate_histogram('class').getInfo()

                if len(classHistogram) == 1:
                    # smileRandomForest requires >=2 classes ("Only one class" error).
                    # Tiles that are 100% one stable class (e.g. homogeneous primary
                    # forest) get that class assigned directly instead of a classifier.
                    singleClass = int(list(classHistogram.keys())[0])

                    # cast to match classify()'s default int32 output type, so this
                    # collection stays homogeneous when merged downstream (script 5)
                    classification = ee.Image.constant(singleClass) \
                        .toInt() \
                        .updateMask(composite.select(0).mask()) \
                        .rename('classification')
                else:
                    # Train one RF model per grid and year using spectral + embedding features.
                    classifier = ee.Classifier.smileRandomForest(  # type: ignore
                        numberOfTrees=RF_PARAMS['numberOfTrees']
                    ).train(
                        features=samples,
                        classProperty='class',
                        inputProperties=FEAT_SPACE_BANDS + EMBEDDING_BANDS,
                    )

                    classification = composite.classify(classifier)

                classification = classification\
                    .set('grid_name', gridName)\
                    .set('year', year)\
                    .set('version', OUTPUT_VERSION)

                region = geometry.getInfo()['coordinates']

                task = ee.batch.Export.image.toAsset(
                    image=classification,
                    description=imageName,
                    assetId='{}/{}'.format(ASSET_OUTPUT, imageName),
                    pyramidingPolicy={".default": "mode"},
                    region=region,
                    scale=10,
                    maxPixels=1e13
                )

                print('Exporting {}...'.format(imageName))
                
                task.start()
            except Exception as e:
                print(e)
