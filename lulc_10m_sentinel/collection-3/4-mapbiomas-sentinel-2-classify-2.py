"""Sentinel Collection 3 stage 4: classify mosaics by grid and year.

This script loads the training tables generated by stage 3, combines Sentinel
mosaic features with annual embedding bands, trains a Random Forest per grid
and year, and exports classification rasters to Earth Engine assets.

Inputs:
- Sentinel-2 mosaic collections filtered by biome and mosaic version
- Training table assets under `.../SAMPLES/AMAZONIA/TRAINED`
- `GOOGLE/SATELLITE_EMBEDDING/V1/ANNUAL` for each processed year

Outputs:
- Classification assets under `.../GENERAL/classification-amz`

Run this after stage 3 and before the temporal filter in stage 5. The
single-class fallback is intentional and should be preserved to avoid
classifier failures on homogeneous tiles.
"""
